//! Generates the extent daemon's gRPC API (`proto/cladefs/cladefsd/v1/cladefsd.proto`), what
//! daemons sharing a bucket serve each other (`proto/cladefs/peer/v1/peer.proto`, TASK-406.2), and
//! the API of FUSE mounts of many cells (`proto/cladefs/mount/v1/mount.proto`), with protox, which
//! compiles protobuf in Rust: no protoc needed; for tonic, and for madsim's tonic. cladefs: and
//! stamps the build with the commit it is of (`CLADEFS_BUILD_COMMIT`, [`crate::BUILD_COMMIT`]), as
//! scripts/build-commit.sh says, which every build of the tree reports (TASK-111.7), refuses a
//! release build without frame pointers (`build/stamp.rs`), and has a release build's binaries
//! link with their debug sections compressed (board 10269).

use std::path::PathBuf;

// What the build stamps, and checks of it (board 8597, board 8599).
#[path = "build/stamp.rs"]
mod stamp;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    stamp::require_frame_pointers()?;
    compress_debug_sections()?;
    let protos = [
        "proto/cladefs/cladefsd/v1/cladefsd.proto",
        "proto/cladefs/peer/v1/peer.proto",
        "proto/cladefs/mount/v1/mount.proto",
    ];
    for proto in protos {
        println!("cargo:rerun-if-changed={proto}");
    }
    // Compiled by protox, then generated twice from its descriptors by madsim's tonic-build: as
    // tonic has it, and, in `$OUT_DIR/sim`, as madsim's simulated tonic has it, which the build
    // under `--cfg madsim` includes (doc-24, TASK-685.12).
    let mut compiler = protox::Compiler::new(["proto"])?;
    compiler.include_imports(true).include_source_info(true).open_files(protos)?;
    let out = PathBuf::from(std::env::var("OUT_DIR")?);
    let set = out.join("protos.bin");
    std::fs::write(&set, compiler.encode_file_descriptor_set())?;
    // Each service of cladefs's own files (imported ones, Google's, serve none of the daemon's),
    // by its full name, with its file and its methods' names.
    let services: Vec<(String, String, Vec<String>)> = (compiler.file_descriptor_set().file)
        .iter()
        .filter(|file| file.package().starts_with("cladefs."))
        .flat_map(|file| {
            file.service.iter().map(|service| {
                let full = format!("{}.{}", file.package(), service.name());
                let methods = service.method.iter().map(|method| method.name().to_owned());
                (full, file.name().to_owned(), methods.collect())
            })
        })
        .collect();
    std::fs::write(out.join("grpc_services.rs"), services_rs(&services))?;
    madsim_tonic_build::configure()
        .file_descriptor_set_path(&set)
        .skip_protoc_run()
        .compile_protos(&protos, &["proto"])?;
    stamp::stamp_commit()
}

/// cladefs: has a release build's binaries (cladefsd, cladefsctl, cladefs-mount) on Linux link
/// with their debug sections compressed (board 10269): the release profile's line tables, which
/// `/z/pprof` names each frame's file and line by, took cladefsd from 61 MB to 281 MB, most of it
/// the C dependencies' and std's debug info. zlib (`SHF_COMPRESSED`), which GNU ld and lld both
/// write and the backtrace crate resolving `/z/pprof`'s frames reads; zstd only with its `ruzstd`
/// feature, off here. Tests' and debug builds link as they were, sparing every test's link the
/// compression. cladefsd 293 MB -> 105 MB, its frames still named by file and line (hotbed question
/// 558).
fn compress_debug_sections() -> Result<(), Box<dyn std::error::Error>> {
    if std::env::var("PROFILE")? == "release" && std::env::var("CARGO_CFG_TARGET_OS")? == "linux" {
        println!("cargo:rustc-link-arg-bins=-Wl,--compress-debug-sections=zlib");
    }
    Ok(())
}

/// cladefs: `services`, each by its full name, with its file and its methods' names, as Rust: a
/// `Service` constant of each, named as the service is, in capitals, its methods by their paths,
/// and `SERVICES`, all of them, which the daemon's metrics and spans of its calls name them by
/// (`cladefsd::grpc`, board 8565), so that a method added to a .proto is counted with no more
/// code, and none a caller makes up is.
fn services_rs(services: &[(String, String, Vec<String>)]) -> String {
    use std::fmt::Write as _;
    let mut out = String::from("// Generated by build.rs from the .protos' descriptors.\n");
    let mut names = Vec::new();
    for (full, file, methods) in services {
        let constant = full.rsplit('.').next().unwrap_or(full).to_uppercase();
        let _ = writeln!(out, "/// `{full}`, of `{file}`.");
        let _ = writeln!(out, "pub const {constant}: Service = Service {{");
        let _ = writeln!(out, "    name: {full:?},");
        let _ = writeln!(out, "    methods: &[");
        for method in methods {
            let _ = writeln!(out, "        {:?},", format!("/{full}/{method}"));
        }
        let _ = writeln!(out, "    ],\n}};");
        names.push(constant);
    }
    let _ = writeln!(out, "/// Every service of the daemon's .protos.");
    let _ =
        writeln!(out, "pub const SERVICES: [Service; {}] = [{}];", names.len(), names.join(", "));
    out
}
